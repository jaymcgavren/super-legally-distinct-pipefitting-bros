# Segment library for tools/gen-levels.rb. Each segment is 20 columns x 10
# rows (row 0 = top, rows 8-9 = ground). Legend is in app/levels.rb.
#
#   seg(name, kind, difficulty, *rows)
#   kind: :out_start :out :out_goal   (outdoor rooftops)
#         :in_start  :in  :in_goal    (inside a building; row 0 is ceiling)
#         :arena  :in_arena           (boss arena, last segment of every level)
#   difficulty: 1 easy .. 3 hard
SEGMENTS = {}
def seg(name, kind, diff, *rows)
  raise "#{name}: need 10 rows" unless rows.size == 10
  rows.each { |r| raise "#{name}: row #{r.inspect} not 20 wide" unless r.size == 20 }
  SEGMENTS[name] = { kind: kind, diff: diff, rows: rows }
end

