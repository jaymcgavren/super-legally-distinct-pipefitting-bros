# Builds app/levels.rb: 2 jobsites x sections A-D from tools/segments.rb.
#   A  rooftops by day      B  inside a building (day, then sunset outside)
#   C  rooftops at sunset   D  rooftops at night
# Every level ends in a boss arena (indoors for B), and Big Rusty learns one
# more move each level: 1-A is boss 1, 2-D is boss 8. Later jobsites draw
# harder segments, mirror some, and add enemies. Every level is checked with
# tools/reach.rb; a level that fails is rerolled.
#   ruby tools/gen-levels.rb            (all)    ruby tools/gen-levels.rb 5 6
require_relative 'segments'

WORLDS = 2
TITLES = [
  ['ROOFTOP ROW', 'BOILER ROOM', 'SUNSET STACKS', 'RUSTY YARD'],
  ['WATER HAMMER', 'MECHANICAL ROOM', 'HOT AND HUMID', 'THE FINAL VALVE'],
]
THEME = %i[day indoor dusk night]
# the time of day seen through the windows of each jobsite's B building
INDOOR_TIME = %i[indoor indoor_dusk]
OUT = File.expand_path('../app/levels.rb', __dir__)

def pool(kind, world)
  lo, hi = case world
           when 1 then [1, 1]
           when 2 then [1, 2]
           when 3..5 then [1, 3]
           else [2, 3]
           end
  SEGMENTS.select { |_, s| s[:kind] == kind && s[:diff].between?(lo, hi) }.keys
end

def pick(rng, kind, world, n)
  names = pool(kind, world).shuffle(random: rng)
  names += SEGMENTS.select { |_, s| s[:kind] == kind }.keys.shuffle(random: rng) while names.size < n
  names.first(n)
end

def build(world, sec, seed)
  rng = Random.new(seed)
  indoor = sec == 1
  boss = true
  pre = indoor ? :in : :out
  # A-C keep the length (and the random draws) they had before every level got
  # a boss, so their layouts are unchanged up to the arena
  n_mid = sec == 3 ? 6 : 8
  starts = SEGMENTS.select { |_, s| s[:kind] == :"#{pre}_start" }.keys
  goals = SEGMENTS.select { |_, s| s[:kind] == :"#{pre}_goal" }.keys
  names = [starts.sample(random: rng)] + pick(rng, pre, world, n_mid)
  goals.sample(random: rng) if sec != 3
  names << (indoor ? :in_arena : :arena)
  segs = names.each_with_index.map do |nm, i|
    rows = SEGMENTS[nm][:rows].map(&:dup)
    mid = i > 0 && i < names.size - 1
    rows = rows.map(&:reverse) if mid && world >= 3 && rng.rand < 0.35
    rows = rows.map { |r| r.tr('K', '.') } if mid
    rows
  end
  rows = Array.new(10) { |r| segs.map { |s| s[r] }.join }
  cols = rows[0].size
  # a checkpoint in the middle of the level (and one before a boss arena)
  spots = [(names.size / 2) * 20]
  spots << (names.size - 2) * 20 if boss
  spots.each do |seg_c|
    (seg_c + 1..seg_c + 18).each do |c|
      next unless rows[7][c] == '.' && rows[7][c + 1] == '.' && '#F'.include?(rows[8][c])
      next unless rows[6][c] == '.'
      rows[7][c] = 'K'
      break
    end
  end
  # make sure there is a wrench crate somewhere in the first half
  unless rows.any? { |r| r[0, cols / 2].include?('W') }
    rows.each { |r| i = r.index('C'); (r[i] = 'W'; break) if i && i < cols / 2 }
  end
  # tougher crews later on: more crabs, extra enemies on open floor
  rows.each { |r| r.size.times { |c| r[c] = 'v' if r[c] == 'r' && rng.rand < (world - 1) * 0.07 } }
  extra = [world - 2, 0].max
  tries = 0
  while extra > 0 && (tries += 1) < 400
    c = 30 + rng.rand(cols - 30 - (boss ? 24 : 12))
    next unless rows[7][c] == '.' && '#F'.include?(rows[8][c]) && rows[6][c] == '.'
    next if (c - 3..c + 3).any? { |k| 'rvKSG'.include?(rows[7][k]) }
    rows[7][c] = rng.rand < 0.3 + world * 0.05 ? 'v' : 'r'
    extra -= 1
  end
  { name: "JOBSITE #{world}-#{'ABCD'[sec]}", title: TITLES[world - 1][sec], theme: sec == 1 ? INDOOR_TIME[world - 1] : THEME[sec],
    boss: (world - 1) * 4 + sec + 1, time: 400, segs: names, rows: rows }
end

def write(levels)
  File.open(OUT, 'w') do |f|
    f.puts '# GENERATED by tools/gen-levels.rb from tools/segments.rb -- edit those, then rerun.'
    f.puts '#'
    f.puts '#   #  brick                =  steel girder         -  copper pipe (one-way)'
    f.puts '#   |  pipe stand (decor)   C  crate: brass nut     M  crate: many nuts'
    f.puts '#   W  crate: pipe wrench   I  hidden crate: 1UP    o  brass nut'
    f.puts '#   S  steam vent           L  vertical lift        H  horizontal lift'
    f.puts '#   r  rust blob            v  valve-crab           K  checkpoint cone'
    f.puts '#   P  player start         G  main shutoff valve   F  wood floor (indoors)'
    f.puts '#   B  boss spawn (arena)'
    f.puts 'LEVELS = ['
    levels.each do |lv|
      f.puts "  { name: '#{lv[:name]}', title: '#{lv[:title]}', theme: :#{lv[:theme]}, " \
             "boss: #{lv[:boss].inspect}, time: #{lv[:time]},"
      f.puts "    # #{lv[:segs].join(' ')}"
      f.puts '    rows: ['
      lv[:rows].each { |r| f.puts "      '#{r}'," }
      f.puts '    ] },'
    end
    f.puts ']'
  end
end

if __FILE__ == $0
  require_relative 'reach'
  only = ARGV.map(&:to_i)
  seeds = {}
  levels = []
  WORLDS.times do |w|
    4.times do |sec|
      idx = w * 4 + sec
      seeds[idx] = 1000 + idx * 17
      levels << build(w + 1, sec, seeds[idx])
    end
  end
  write(levels)
  targets = only.empty? ? (0...levels.size).to_a : only
  targets.each do |idx|
    8.times do |attempt|
      $VERBOSE = nil
      load OUT
      ok, n, = analyze(idx)
      puts "#{levels[idx][:name]} #{levels[idx][:title]}: #{ok ? 'ok' : 'UNREACHABLE'} (#{n} spots, seed #{seeds[idx]})"
      break if ok
      seeds[idx] += 7919
      levels[idx] = build(idx / 4 + 1, idx % 4, seeds[idx])
      write(levels)
      raise "#{levels[idx][:name]}: no reachable layout" if attempt == 7
    end
  end
end
